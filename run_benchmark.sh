#!/usr/bin/env bash
#
# run_benchmark.sh - build and run the comprehensive LQOI lossy benchmark.
#
# This script keeps all third-party/build-time dependencies out of the tracked
# repo. It fetches stb_image headers and the upstream (strictly lossless) QOI
# reference into a gitignored vendor/ directory, fetches the Kodak True Color
# image suite as the default dataset, builds lqoibench, and runs it.
#
# Usage:
#   ./run_benchmark.sh [dataset_dir] [-- extra lqoibench args]
#
# Defaults to the Kodak suite in images/kodak. Results land in results/.

set -euo pipefail
cd "$(dirname "$0")"

VENDOR=vendor
RESULTS=results
DATASET="${1:-images/kodak}"
shift || true
EXTRA_ARGS=()
if [ "${1:-}" = "--" ]; then shift; EXTRA_ARGS=("$@"); fi

mkdir -p "$VENDOR" "$RESULTS"

# --- 1. fetch build-time headers (not vendored in git) -----------------------
fetch() { # url dest
	if [ ! -s "$2" ]; then
		echo "fetching $(basename "$2") ..."
		curl -sfL -o "$2" "$1"
	fi
}
fetch https://raw.githubusercontent.com/nothings/stb/master/stb_image.h        "$VENDOR/stb_image.h"
fetch https://raw.githubusercontent.com/nothings/stb/master/stb_image_write.h  "$VENDOR/stb_image_write.h"
fetch https://raw.githubusercontent.com/phoboslab/qoi/master/qoi.h             "$VENDOR/qoi_orig.h"

# --- 2. generate the renamed lossless-QOI baseline TU (gitignored) -----------
# The reference implementation is NOT committed to this repo; we compile it
# from the upstream header with its public symbols renamed so it can be linked
# next to the LQOI implementation in qoi.h.
cat > "$VENDOR/qoi_ref.c" <<'EOF'
/* Auto-generated by run_benchmark.sh. Strictly-lossless QOI size baseline,
   compiled from upstream phoboslab/qoi with renamed public symbols. */
#define QOI_IMPLEMENTATION
#define QOI_NO_STDIO
#define qoi_encode qoiref_encode
#define qoi_decode qoiref_decode
#define qoi_desc   qoiref_desc
#include "qoi_orig.h"
EOF

# --- 3. fetch the default dataset (Kodak True Color suite) -------------------
if [ "$DATASET" = "images/kodak" ] && [ ! -d images/kodak ]; then
	echo "fetching Kodak True Color suite (24 images) ..."
	mkdir -p images/kodak
	for i in $(seq -w 1 24); do
		curl -sfL -o "images/kodak/kodim${i}.png" \
			"http://r0k.us/graphics/kodak/kodak/kodim${i}.png" &
	done
	wait
fi
if [ ! -d "$DATASET" ]; then
	echo "ERROR: dataset directory '$DATASET' not found." >&2
	exit 1
fi

# --- 4. build ----------------------------------------------------------------
CC="${CC:-cc}"
PNG_CFLAGS="$(pkg-config --cflags libpng 2>/dev/null || true)"

echo "building lqoibench ..."
# compile the renamed lossless baseline object
$CC -std=c99 -O3 -I"$VENDOR" -c "$VENDOR/qoi_ref.c" -o "$VENDOR/qoi_ref.o"
# compile the benchmark, linking the baseline (-DLQOI_WITH_REF enables it)
# shellcheck disable=SC2086
$CC -std=gnu99 -O3 -DLQOI_WITH_REF -I"$VENDOR" -I. $PNG_CFLAGS \
	lqoibench.c "$VENDOR/qoi_ref.o" -lm -o lqoibench

# --- 5. run ------------------------------------------------------------------
echo "running benchmark on $DATASET ..."
echo
./lqoibench "$DATASET" --outdir "$RESULTS" ${EXTRA_ARGS[@]+"${EXTRA_ARGS[@]}"}
